// ─── Language state ───────────────────────────────────────────
// `currentLang` is exported as a live `let` binding — importing
// modules read its current value on every access (ES module live
// bindings), so we never need a getter or window global.

export let currentLang = localStorage.getItem('lang') || 'he';

export function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key])
      || TRANSLATIONS.en[key]
      || key;
}

// Pure language switch — updates state + DOM + localStorage. Does
// NOT trigger a re-render: that's the entry module's job (see
// app.js's setLanguage bridge wrapper). Splitting these concerns
// avoids a module cycle between i18n and app.
export function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir  = lang === 'he' ? 'rtl' : 'ltr';
  localStorage.setItem('lang', lang);
}

